import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { afterEach, describe, expect, it } from 'vitest';

const roots: string[] = [];
const script = join(process.cwd(), 'scripts/plugins-sync.mjs');
function fixture(entries = ['./plugins/beta', '@greenhouse/plugin-alpha']) {
  const root = mkdtempSync(join(tmpdir(), 'gh-plugin-sync-'));
  roots.push(root);
  writeFileSync(join(root, 'package.json'), JSON.stringify({ type: 'module' }));
  writeFileSync(join(root, 'greenhouse.config.ts'), `export default ${JSON.stringify({ plugins: entries })}`);
  for (const dir of ['apps/api/src/plugin-host', 'apps/web/src/extensions'])
    mkdirSync(join(root, dir), { recursive: true });
  for (const id of ['alpha', 'beta']) {
    const dir = join(root, 'plugins', id);
    mkdirSync(dir, { recursive: true });
    writeFileSync(
      join(dir, 'package.json'),
      JSON.stringify({
        name: `@greenhouse/plugin-${id}`,
        version: '1.0.0',
        greenhouse: { id, sdk: 1, api: './api.ts' },
        exports: { './api': './api.ts' },
      }),
    );
    writeFileSync(
      join(dir, 'manifest.ts'),
      `export default ${JSON.stringify({ id, name: id, sdk: 1, version: '1.0.0', dependsOn: [] })}`,
    );
    writeFileSync(join(dir, 'api.ts'), `throw new Error('sync must not execute code halves'); export default {};`);
  }
  return root;
}
function sync(root: string, check = false, override?: string) {
  const code = `import { syncPlugins } from ${JSON.stringify(script)}; await syncPlugins({ root: ${JSON.stringify(root)}, check: ${check}, env: ${JSON.stringify(override === undefined ? {} : { GREENHOUSE_PLUGINS: override })} });`;
  return execFileSync(process.execPath, ['--import', 'tsx', '--input-type=module', '-e', code], {
    cwd: process.cwd(),
    encoding: 'utf8',
    stdio: 'pipe',
  });
}
function change(root: string, id: string, key: string, value: unknown) {
  const path = join(root, 'plugins', id, 'package.json');
  const data = JSON.parse(readFileSync(path, 'utf8'));
  data.greenhouse[key] = value;
  writeFileSync(path, JSON.stringify(data));
}
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

describe('plugins:sync', () => {
  it('assembles paths and workspace names in config order, without executing either half', () => {
    const root = fixture();
    expect(() => sync(root, true)).toThrow(/missing or stale/);
    sync(root);
    const output = readFileSync(join(root, 'apps/api/src/plugin-host/compiled.generated.ts'), 'utf8');
    expect(output).toContain('generated by pnpm plugins:sync — do not edit');
    expect(output.indexOf('beta/api.js')).toBeLessThan(output.indexOf('alpha/api.js'));
    sync(root, true);
    expect(readFileSync(join(root, 'apps/web/src/extensions/compiled.generated.ts'), 'utf8')).toContain('= []');
    writeFileSync(join(root, 'apps/web/src/extensions/compiled.generated.ts'), '// stale');
    expect(() => sync(root, true)).toThrow(/missing or stale/);
  });

  it('assembles matching candidate versions and rejects mismatched or incomplete versions', () => {
    const root = fixture(['./plugins/alpha']);
    const pkgPath = join(root, 'plugins/alpha/package.json');
    const manifestPath = join(root, 'plugins/alpha/manifest.ts');
    const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
    pkg.version = '4.0.0-rc.1';
    writeFileSync(pkgPath, JSON.stringify(pkg));
    const manifest = { id: 'alpha', name: 'Alpha', sdk: 1, version: pkg.version, dependsOn: [] };
    writeFileSync(manifestPath, `export default ${JSON.stringify(manifest)}`);
    sync(root);
    expect(readFileSync(join(root, 'apps/api/src/plugin-host/compiled.generated.ts'), 'utf8')).toContain(
      "version: '4.0.0-rc.1'",
    );
    for (const version of ['4.0.0-rc.2', '4.0', 'v4.0.0', 'invalid']) {
      writeFileSync(manifestPath, `export default ${JSON.stringify({ ...manifest, version })}`);
      expect(() => sync(root)).toThrow(/version matching package.json/);
    }
  });

  it('supports an empty compiled set and optional halves', () => {
    const root = fixture();
    sync(root, false, '');
    expect(readFileSync(join(root, 'apps/api/src/plugin-host/compiled.generated.ts'), 'utf8')).toContain('= []');
    sync(root, true, '');
  });

  it('resolves an installed web-only package with a hidden package.json', () => {
    const root = fixture(['@private/plugin-gamma']);
    const dir = join(root, 'node_modules/@private/plugin-gamma');
    mkdirSync(dir, { recursive: true });
    writeFileSync(
      join(dir, 'package.json'),
      JSON.stringify({
        name: '@private/plugin-gamma',
        type: 'module',
        version: '1.0.0',
        greenhouse: { id: 'gamma', sdk: 1, web: './web.js' },
        exports: { './manifest': { import: './manifest.js' }, './web': { import: './web.js' } },
      }),
    );
    writeFileSync(
      join(dir, 'manifest.js'),
      "export default { id: 'gamma', name: 'Gamma', sdk: 1, version: '1.0.0', dependsOn: [] };",
    );
    writeFileSync(join(dir, 'web.js'), "throw new Error('do not execute'); export default {};");
    sync(root);
    expect(readFileSync(join(root, 'apps/web/src/extensions/compiled.generated.ts'), 'utf8')).toContain(
      '@private/plugin-gamma/web',
    );
    expect(readFileSync(join(root, 'apps/api/src/plugin-host/compiled.generated.ts'), 'utf8')).toContain("id: 'gamma'");
    sync(root, true);
  });

  it('rejects duplicate ids, unsupported SDKs, missing exports and folder mismatches', () => {
    const duplicate = fixture(['./plugins/alpha', './plugins/alpha']);
    expect(() => sync(duplicate)).toThrow(/listed twice/);
    const unsupported = fixture();
    change(unsupported, 'beta', 'sdk', 3);
    expect(() => sync(unsupported)).toThrow(/unsupported sdk/);
    const mismatch = fixture();
    change(mismatch, 'beta', 'id', 'other');
    expect(() => sync(mismatch)).toThrow(/match its folder/);
    const exports = fixture();
    change(exports, 'beta', 'api', './manifest.ts');
    expect(() => sync(exports)).toThrow(/declared in exports/);
  });

  it('rejects manifest mismatches, non-data values and missing or cyclic dependencies', () => {
    const root = fixture();
    const path = join(root, 'plugins/beta/manifest.ts');
    writeFileSync(path, "export default { id: 'wrong', sdk: 1 }");
    expect(() => sync(root)).toThrow(/does not match/);
    writeFileSync(path, "export default { id: 'beta', sdk: 1, callback: () => {} }");
    expect(() => sync(root)).toThrow(/JSON-serialisable/);
    writeFileSync(path, "export default { id: 'beta', name: 'b', version: '1.0.0', sdk: 1, dependsOn: ['missing'] }");
    expect(() => sync(root)).toThrow(/not listed/);
    writeFileSync(path, "export default { id: 'beta', name: 'b', version: '1.0.0', sdk: 1, dependsOn: ['alpha'] }");
    writeFileSync(
      join(root, 'plugins/alpha/manifest.ts'),
      "export default { id: 'alpha', name: 'a', version: '1.0.0', sdk: 1, dependsOn: ['beta'] }",
    );
    expect(() => sync(root)).toThrow(/dependency cycle/);
  });
});

it('assembles SDK 1 and SDK 2 packages in the same station', () => {
  const root = fixture();
  change(root, 'alpha', 'sdk', 2);
  writeFileSync(
    join(root, 'plugins/alpha/manifest.ts'),
    "export default { id: 'alpha', name: 'Alpha', sdk: 2, version: '1.0.0', dependsOn: [], surfaces: { nav: [], pages: [] } }",
  );
  sync(root);
  expect(readFileSync(join(root, 'apps/api/src/plugin-host/compiled.generated.ts'), 'utf8')).toContain('alpha/api.js');
});

it('resolves manifest UI paths independently of cwd and refuses paths outside the package', () => {
  const root = fixture();
  const manifest = join(root, 'plugins/beta/manifest.ts');
  mkdirSync(join(root, 'plugins/beta/ui'));
  writeFileSync(
    manifest,
    "export default { id: 'beta', name: 'Beta', sdk: 1, version: '1.0.0', dependsOn: [], ui: './ui' }",
  );
  sync(root);
  const output = readFileSync(join(root, 'apps/api/src/plugin-host/compiled.generated.ts'), 'utf8');
  expect(output).toContain('fileURLToPath(new URL(');
  expect(output).toContain('plugins/beta/ui');
  expect(output).toContain('/ext/beta/ui/');
  // A manifest/static frontend does not need either compiled code half.
  change(root, 'beta', 'api', undefined);
  sync(root);
  const uiOnly = readFileSync(join(root, 'apps/api/src/plugin-host/compiled.generated.ts'), 'utf8');
  expect(uiOnly).toContain('plugins/beta/ui');
  expect(uiOnly).toContain('/ext/beta/ui/');
  writeFileSync(
    manifest,
    "export default { id: 'beta', name: 'Beta', sdk: 1, version: '1.0.0', dependsOn: [], ui: './../alpha' }",
  );
  expect(() => sync(root)).toThrow(/inside the plugin/);
});
