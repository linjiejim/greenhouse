/** Run from the repository root: node --import tsx apps/mobile/scripts/build-status-palette.mjs */
import { writeFileSync } from 'node:fs';
import { URL } from 'node:url';
import { color } from '../../../packages/ui/src/tokens/haven.ts';
const roles = { red: 'danger', orange: 'warning', green: 'success', blue: 'info' };
const palette = Object.fromEntries(
  ['light', 'dark'].map((mode) => [
    mode,
    Object.fromEntries(
      Object.entries(roles).flatMap(([native, role]) => [
        [native, color[role][mode]],
        [native + 'Fill', color[role + 'Fill'][mode]],
      ]),
    ),
  ]),
);
writeFileSync(
  new URL('../src/theme/status.generated.ts', import.meta.url),
  '/** GENERATED by apps/mobile/scripts/build-status-palette.mjs from Haven status roles. */\n' +
    'export const nativeStatus = ' +
    JSON.stringify(palette, null, 2) +
    ';\n',
);
