#!/usr/bin/env node
/**
 * noVNC for the phone's computer viewer — bundles the web app's `@novnc/novnc`
 * (one version for both clients) into a single ES module and writes it as a
 * string constant the viewer page inlines (src/bots/computer/viewer-html.ts):
 *
 *   node apps/mobile/scripts/build-novnc.mjs        # from the repo root
 *
 * Why a generated string: the viewer runs in the WebView the app already ships
 * (react-native-webview), so the library must travel inside the JS bundle — an
 * OTA update, no new native dependency, no CDN (the computer is a core feature
 * and self-hosted stations may have no route to one). Re-run after upgrading
 * noVNC in apps/web; src/bots/computer/novnc-bundle.parity.test.ts turns red
 * until the versions match again.
 *
 * Needs the root workspace's install (esbuild is resolved through tsx, which
 * depends on it; apps/mobile itself stays out of the workspace).
 */

import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { URL, fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const OUT = fileURLToPath(new URL('../src/bots/computer/novnc.generated.ts', import.meta.url));

const rootRequire = createRequire(`${ROOT}package.json`);
const esbuild = createRequire(rootRequire.resolve('tsx/package.json'))('esbuild');
// The package exports only its entry (core/rfb.js); its package.json is one folder up.
const entry = createRequire(`${ROOT}apps/web/package.json`).resolve('@novnc/novnc');
const { version, license } = JSON.parse(readFileSync(new URL('../package.json', `file://${entry}`), 'utf8'));

// noVNC 1.5+ awaits a WebCodecs probe at the top level, so the bundle stays an
// ES module (the page loads it with <script type="module">). It announces
// itself on window once that await has settled.
const result = await esbuild.build({
  stdin: {
    contents: `import RFB from ${JSON.stringify(entry)};\nwindow.RFB = RFB;\nwindow.dispatchEvent(new Event('rfb-ready'));\n`,
    resolveDir: ROOT,
    loader: 'js',
  },
  bundle: true,
  format: 'esm',
  minify: true,
  target: 'safari16',
  legalComments: 'none',
  write: false,
  banner: { js: `/* noVNC ${version} (${license}, unmodified) — https://github.com/novnc/noVNC */` },
});
const source = result.outputFiles[0].text;

writeFileSync(
  OUT,
  `// GENERATED by apps/mobile/scripts/build-novnc.mjs from apps/web's @novnc/novnc — do not edit.
// Regenerate from the repo root after a noVNC upgrade: node apps/mobile/scripts/build-novnc.mjs
export const NOVNC_VERSION = ${JSON.stringify(version)};
export const NOVNC_SOURCE = ${JSON.stringify(source)};
`,
);
console.log(`noVNC ${version}: ${(source.length / 1024).toFixed(0)} KB → ${OUT.slice(ROOT.length)}`);
